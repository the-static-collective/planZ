import crypto from "node:crypto";
import { proposeInstrument } from "./instrument-engine.mjs";
import {
  createTransitionReceipt,
  transitionChainId,
  verifyTransitionChain
} from "../../arrow/src/transition-engine.mjs";

function sha256Text(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function digest(value) {
  return {algorithm:"sha256",value};
}

export function buildLulArrowChain(real,human,completion,{humanText=null,completionText=null}={}) {
  if (!real?.source?.sha256 || !real?.organ?.organId) throw new Error("real witness incomplete");
  if (!human?.receiptSha256 || !completion?.derivedHumanPerformanceArtifact?.sha256) {
    throw new Error("human/completion witness incomplete");
  }

  const sourceRef=`artifact:sha256:${real.source.sha256}`;
  const humanRepoDigest=humanText ? sha256Text(humanText) : null;

  const organ={
    organId:real.organ.organId,
    kind:real.organ.kind,
    description:real.organ.description,
    behavior:real.instrument.proposal,
    basisRefs:[
      `sha256:${real.source.sha256}`,
      `repeat-window:${real.source.repeatWindowsSeconds[0].join("-")}`,
      `repeat-window:${real.source.repeatWindowsSeconds[1].join("-")}`
    ],
    candidateDestinations:["PLANZ-003 playable organ"]
  };

  const proposal=proposeInstrument({
    artifactId:sourceRef,
    sourceRefs:[`sha256:${real.source.sha256}`]
  },organ);

  const observe=createTransitionReceipt({
    kind:"OBSERVE",
    operation:"Identify an explicit reusable organ from the admitted finished artifact.",
    inputs:[{role:"source-artifact",ref:sourceRef,digest:digest(real.source.sha256)}],
    outputs:[{role:"explicit-organ",ref:organ.organId}],
    claims:["The repeated LOW → UP → LOW chorus geometry was explicitly identified as an organ."],
    nonClaims:["Observation does not authorize reuse.","Organ identity does not transfer ownership."]
  });

  const propose=createTransitionReceipt({
    kind:"PROPOSE",
    operation:"Convert the explicit organ into a deterministic non-authoritative InstrumentProposal.",
    inputs:[
      {role:"source-artifact",ref:sourceRef,digest:digest(real.source.sha256)},
      {role:"explicit-organ",ref:organ.organId}
    ],
    outputs:[{role:"instrument-proposal",ref:`proposal:${proposal.proposalId}`}],
    predecessorReceiptIds:[observe.receiptId],
    claims:["The InstrumentProposal was generated by the repository-owned deterministic proposal engine."],
    nonClaims:["Proposal does not select itself.","Proposal does not prove destination capability."]
  });

  const admit=createTransitionReceipt({
    kind:"ADMIT",
    operation:"Record the external human decision to run the proposed instrument.",
    inputs:[{role:"instrument-proposal",ref:`proposal:${proposal.proposalId}`}],
    outputs:[{role:"admission",ref:"admission:planz-003-real-001"}],
    predecessorReceiptIds:[propose.receiptId],
    admission:{
      decision:"ACCEPT",
      authorityRef:"003/witnesses/l-to-u-to-l-real-001.json#instrument.selectionAuthority"
    },
    claims:["The checked-in real witness records that the human operator requested the PLANZ-003 run."],
    nonClaims:["The TransitionReceipt does not create that authority.","Admission does not prove performance."]
  });

  const humanInputs=[
    {role:"original-human-play-upload",ref:`upload:sha256:${human.receiptSha256}`,digest:digest(human.receiptSha256)},
    {role:"normalized-human-play-witness",ref:"003/witnesses/l-to-u-to-l-human-play-001.json",
      digest:humanRepoDigest ? digest(humanRepoDigest) : null}
  ];

  const perform=createTransitionReceipt({
    kind:"PERFORM",
    operation:"Apply the admitted instrument using the returned human controller events and render the resulting artifact.",
    inputs:[
      {role:"admission",ref:"admission:planz-003-real-001"},
      ...humanInputs
    ],
    outputs:[{
      role:"result-artifact",
      ref:`artifact:sha256:${completion.derivedHumanPerformanceArtifact.sha256}`,
      digest:digest(completion.derivedHumanPerformanceArtifact.sha256)
    }],
    predecessorReceiptIds:[admit.receiptId],
    claims:[
      "A human controller performance was captured.",
      "The original uploaded receipt identity and the normalized repository witness identity are preserved separately.",
      "The derived result artifact is identified by the completion receipt hash."
    ],
    nonClaims:[
      "The normalized checked-in JSON is not claimed byte-identical to the original uploaded human receipt.",
      "The repository does not currently embed the result artifact bytes.",
      "Performance does not imply ancestry authorized the new work."
    ]
  });

  const completionDigest=completionText ? sha256Text(completionText) : null;
  const returnReceipt=createTransitionReceipt({
    kind:"RETURN",
    operation:"Return the human performance consequence to planZ as provenance without promoting ancestry to authority.",
    inputs:[{
      role:"result-artifact",
      ref:`artifact:sha256:${completion.derivedHumanPerformanceArtifact.sha256}`,
      digest:digest(completion.derivedHumanPerformanceArtifact.sha256)
    }],
    outputs:[{
      role:"completion-receipt",
      ref:"003/witnesses/l-to-u-to-l-completion-001.json",
      digest:completionDigest ? digest(completionDigest) : null
    }],
    predecessorReceiptIds:[perform.receiptId],
    claims:["The first real PLANZ-003 witness returned a provenance completion receipt."],
    nonClaims:[
      "Return does not imply every PLANZ-003 destination integration is implemented.",
      "Provenance does not grant ownership or authority."
    ]
  });

  const receipts=[observe,propose,admit,perform,returnReceipt];
  const check=verifyTransitionChain(receipts);
  if (!check.valid) throw new Error(check.errors.join("; "));

  return {
    schema:"static-collective/planz-transition-chain/v0",
    chainId:transitionChainId(receipts),
    witnessId:real.witnessId,
    proposal,
    receipts,
    receiptAuthority:"none"
  };
}
